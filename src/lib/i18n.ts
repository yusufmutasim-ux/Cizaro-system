/** Tasks created before the English version stored the Arabic label; map them to keys. */
export function normalizeType(v: string): TypeKey {
  if (v in TYPE_LABELS) return v as TypeKey;
  const hit = TYPE_KEYS.find((k) => TYPE_LABELS[k].ar === v);
  return hit ?? "other";
}
export const typeLabel = (v: string, l: Locale) => TYPE_LABELS[normalizeType(v)][l];
